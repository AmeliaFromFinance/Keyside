// Copies the curated Lucide icons into the client and the companion (for hardware decks).

import { readFileSync, writeFileSync } from "node:fs";

const here = new URL("../", import.meta.url).pathname;
const names = readFileSync(`${here}scripts/icon-list.txt`, "utf8").split(/\s+/).filter(Boolean);
const icons: Record<string, string> = {};
for (const n of names) {
  const svg = readFileSync(`${here}node_modules/lucide-static/icons/${n}.svg`, "utf8");
  const inner = svg.slice(svg.indexOf(">", svg.indexOf("<svg")) + 1, svg.lastIndexOf("</svg>"));
  icons[n] = inner.replace(/\s*\n\s*/g, "").trim();
}
const header = "// Generated by scripts/icons.ts from lucide-static (ISC license). Do not edit.\n";
writeFileSync(`${here}src/lib/icons.gen.ts`, `${header}export const icons: Record<string, string> = ${JSON.stringify(icons)};\n`);
writeFileSync(`${here}../../crates/companion/assets/icons.json`, JSON.stringify(icons) + "\n");
console.log(`${names.length} icons`);
